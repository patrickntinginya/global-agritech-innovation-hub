// Generates supabase/seed.sql from the Phase 1 demonstration data in src/data.
// Repeatable: every statement is an upsert, so running the seed twice changes nothing.
// All rows are marked is_sample = true and status = 'published'. Real content never uses that flag.
// Usage: npm run seed:generate   (then run supabase/seed.sql in the SQL editor, or `supabase db reset`)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const load = (m) => import(path.join(root, 'src/data', `${m}.js`));
const [{ categories }, { countries }, { applications }, { sectors }, { innovations }, { knowledgeItems }, { courses },
  { experts }, { startups }, { opportunities, challenges, organizations }, { discussions }] = await Promise.all(
  ['categories', 'countries', 'taxonomies', 'taxonomies', 'innovations', 'knowledge', 'courses', 'experts', 'startups', 'partnerships', 'discussions'].map(load),
);

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v == null ? 'null' : `$j$${JSON.stringify(v)}$j$::jsonb`);
const arr = (a = []) => (a.length ? `array[${a.map(q).join(',')}]::text[]` : `'{}'::text[]`);
const bi = (v) => (typeof v === 'string' ? { en: v, sw: v } : v);

// Needs per startup: kept from the Phase 1 service so the detail page stays identical.
const needs = {
  s1: { en: ['Pilot farms', 'Distribution partners'], sw: ['Mashamba ya majaribio', 'Washirika wa usambazaji'] },
  s2: { en: ['Veterinary partners', 'Pilot herds'], sw: ['Washirika wa huduma za mifugo', 'Makundi ya majaribio'] },
  s3: { en: ['Farmer groups', 'Grant funding'], sw: ['Vikundi vya wakulima', 'Ufadhili wa ruzuku'] },
  s4: { en: ['Buyers', 'Mobile network partners'], sw: ['Wanunuzi', 'Washirika wa mitandao ya simu'] },
  s5: { en: ['Agronomy partners', 'Pilot farms'], sw: ['Washirika wa kilimo', 'Mashamba ya majaribio'] },
  s6: { en: ['Field data', 'University partners'], sw: ['Data za shambani', 'Washirika wa vyuo'] },
};

const out = [];
const upsert = (table, cols, rows, conflict, update) => {
  if (!rows.length) return;
  out.push(`-- ${table} (${rows.length})`);
  out.push(`insert into public.${table} (${cols.join(', ')}) values`);
  out.push(rows.map((r) => `  (${r.join(', ')})`).join(',\n'));
  out.push(`on conflict (${conflict}) do update set ${update.map((c) => `${c} = excluded.${c}`).join(', ')};\n`);
};

out.push('-- GENERATED by scripts/generate-seed.mjs from the Phase 1 demonstration data. Do not edit by hand.');
out.push('-- Every content row is marked is_sample = true so it can be told apart from real, user-created content.\n');

upsert('sectors', ['id', 'label', 'sort_order'], sectors.map((s, i) => [q(s.id), j(s.label), i]), 'id', ['label', 'sort_order']);
upsert('applications', ['id', 'label', 'sort_order'], applications.map((a, i) => [q(a.id), j(a.label), i]), 'id', ['label', 'sort_order']);
upsert('categories', ['id', 'icon', 'application_ids', 'title', 'blurb', 'consider', 'sort_order'],
  categories.map((c, i) => [q(c.id), q(c.icon), arr(c.applications), j(c.title), j(c.blurb), j(c.consider), i]), 'id',
  ['icon', 'application_ids', 'title', 'blurb', 'consider', 'sort_order']);
upsert('countries', ['id', 'tone', 'name', 'description', 'sort_order'],
  countries.map((c, i) => [q(c.id), q(c.tone), j(c.name), j(c.description), i]), 'id', ['tone', 'name', 'description', 'sort_order']);

const common = ['slug', 'status', 'is_sample'];
const cv = (id) => [q(id), `'published'`, 'true'];

upsert('innovations', [...common, 'sector', 'country_id', 'category_id', 'application_ids', 'title', 'summary', 'benefits', 'considerations', 'added_on'],
  innovations.map((i) => [...cv(i.id), q(i.sector), q(i.countryId), q(i.categoryId), arr(i.applications), j(i.title), j(i.summary), j(i.benefits), j(i.considerations), q(i.added)]),
  'slug', ['sector', 'country_id', 'category_id', 'application_ids', 'title', 'summary', 'benefits', 'considerations', 'added_on']);

upsert('articles', [...common, 'type', 'sector', 'category_ids', 'title', 'summary', 'body', 'minutes', 'published_on'],
  knowledgeItems.map((a) => [...cv(a.id), q(a.type), q(a.sector), arr(a.categoryIds), j(a.title), j(a.summary), j(a.body), a.minutes, q(a.date)]),
  'slug', ['type', 'sector', 'category_ids', 'title', 'summary', 'body', 'minutes', 'published_on']);

upsert('courses', [...common, 'level', 'weeks', 'icon', 'topic', 'related_category_id', 'title', 'description', 'modules'],
  courses.map((c) => [...cv(c.id), q(c.level), c.weeks, q(c.icon), q(c.category), q(c.relatedCategoryId), j(c.title), j(c.description), j(c.modules)]),
  'slug', ['level', 'weeks', 'icon', 'topic', 'related_category_id', 'title', 'description', 'modules']);

upsert('experts', [...common, 'name', 'country_id', 'area', 'area_label', 'bio', 'expertise', 'initial'],
  experts.map((e) => [...cv(e.id), q(e.name), q(e.countryId), q(e.area), j(e.areaLabel), j(e.bio), j(e.expertise), q(e.initial)]),
  'slug', ['name', 'country_id', 'area', 'area_label', 'bio', 'expertise', 'initial']);

upsert('startups', [...common, 'name', 'country_id', 'category_id', 'stage', 'description', 'solutions', 'needs', 'letter'],
  startups.map((s) => [...cv(s.id), q(s.name), q(s.countryId), q(s.categoryId), q(s.stage), j(s.description), j(s.solutions), j(needs[s.id] ?? { en: [], sw: [] }), q(s.letter)]),
  'slug', ['name', 'country_id', 'category_id', 'stage', 'description', 'solutions', 'needs', 'letter']);

upsert('organizations', [...common, 'org_type', 'country_id', 'name', 'summary'],
  organizations.map((o) => [...cv(o.id), q(o.type), q(o.countryId), j(bi(o.name)), j(o.summary)]),
  'slug', ['org_type', 'country_id', 'name', 'summary']);

upsert('partnerships', [...common, 'kind', 'subtype', 'topic', 'phase', 'title', 'summary'],
  [
    ...opportunities.map((o) => [...cv(o.id), q('opportunity'), q(o.type), 'null', q(o.status), j(o.title), j(o.summary)]),
    ...challenges.map((c) => [...cv(c.id), q('challenge'), 'null', q(c.categoryId), q(c.status), j(c.title), j(c.summary)]),
  ],
  'slug', ['kind', 'subtype', 'topic', 'phase', 'title', 'summary']);

upsert('discussions', [...common, 'kind', 'topic', 'title', 'body', 'author_label', 'posted_on'],
  discussions.map((d) => [...cv(d.id), q(d.kind), q(d.topic), j(d.title), j(d.body), j(d.author), q(d.date)]),
  'slug', ['kind', 'topic', 'title', 'body', 'author_label', 'posted_on']);

upsert('discussion_replies', ['discussion_id', 'sample_key', 'status', 'is_sample', 'body', 'accepted', 'author_label'],
  discussions.flatMap((d) => (d.replies ?? []).map((r) => [
    `(select id from public.discussions where slug = ${q(d.id)})`, q(`${d.id}:${r.id}`), `'published'`, 'true', j(r.text), r.accepted ? 'true' : 'false', j(r.author),
  ])),
  'sample_key', ['body', 'accepted', 'author_label']);

out.push(`-- Public site settings (editable by admins in the admin area).
insert into public.site_settings (key, value, is_public) values
  ('seo.default', '{"title":"Global AgriTech Innovation Hub","description":"Discover technologies, knowledge, and partnerships transforming crop farming and livestock production across Africa and the world."}'::jsonb, true),
  ('platform.general', '{"contactEmail":"","maintenanceBanner":{"en":"","sw":""}}'::jsonb, true)
on conflict (key) do nothing;`);

const file = path.join(root, 'supabase', 'seed.sql');
fs.writeFileSync(file, out.join('\n') + '\n');
console.log(`wrote ${path.relative(root, file)} (${out.join('\n').length} bytes)`);
